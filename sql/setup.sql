-- V1 baseline ONLY. For production, immediately run sql/production_v2.sql after this file.
-- V2 removes anonymous enquiry inserts and enforces mandatory editor MFA.
-- Kawalpreet Studio Portfolio -- Supabase setup (run once in SQL Editor).
-- PUBLIC can READ the portfolio and INSERT restricted enquiry records.
-- ONLY pre-approved editors may change the portfolio, read enquiries or upload media.
-- No service-role key is needed in the frontend.

create table if not exists public.portfolio_editors (
  user_id uuid primary key references auth.users (id) on delete cascade,
  created_at timestamptz not null default now()
);
alter table public.portfolio_editors enable row level security;
grant select on public.portfolio_editors to authenticated;
drop policy if exists "Editor can verify own role" on public.portfolio_editors;
create policy "Editor can verify own role" on public.portfolio_editors
  for select to authenticated using (user_id = (select auth.uid()));

create table if not exists public.portfolio_content (
  id smallint primary key default 1 check (id = 1),
  data jsonb not null,
  updated_at timestamptz not null default now()
);
alter table public.portfolio_content enable row level security;
grant select on public.portfolio_content to anon, authenticated;
grant insert, update on public.portfolio_content to authenticated;
drop policy if exists "Anyone can read portfolio" on public.portfolio_content;
create policy "Anyone can read portfolio" on public.portfolio_content
  for select to anon, authenticated using (true);
drop policy if exists "Approved editors insert portfolio" on public.portfolio_content;
create policy "Approved editors insert portfolio" on public.portfolio_content
  for insert to authenticated with check (
    exists (select 1 from public.portfolio_editors e where e.user_id = (select auth.uid()))
  );
drop policy if exists "Approved editors update portfolio" on public.portfolio_content;
create policy "Approved editors update portfolio" on public.portfolio_content
  for update to authenticated
  using (exists (select 1 from public.portfolio_editors e where e.user_id = (select auth.uid())))
  with check (exists (select 1 from public.portfolio_editors e where e.user_id = (select auth.uid())));

create table if not exists public.portfolio_inquiries (
  id bigint generated by default as identity primary key,
  name text not null check (char_length(name) between 1 and 100),
  email text not null check (char_length(email) between 3 and 200 and position('@' in email) > 1),
  company text not null default '' check (char_length(company) <= 120),
  service text not null default '' check (char_length(service) <= 120),
  message text not null check (char_length(message) between 10 and 3000),
  status text not null default 'new' check (status in ('new','read')),
  created_at timestamptz not null default now()
);
alter table public.portfolio_inquiries enable row level security;
grant insert on public.portfolio_inquiries to anon, authenticated;
grant select, update on public.portfolio_inquiries to authenticated;
drop policy if exists "Visitors can send enquiries" on public.portfolio_inquiries;
create policy "Visitors can send enquiries" on public.portfolio_inquiries
  for insert to anon, authenticated with check (status = 'new');
drop policy if exists "Editors can read enquiries" on public.portfolio_inquiries;
create policy "Editors can read enquiries" on public.portfolio_inquiries
  for select to authenticated using (
    exists (select 1 from public.portfolio_editors e where e.user_id = (select auth.uid()))
  );
drop policy if exists "Editors can update enquiry statuses" on public.portfolio_inquiries;
create policy "Editors can update enquiry statuses" on public.portfolio_inquiries
  for update to authenticated
  using (exists (select 1 from public.portfolio_editors e where e.user_id = (select auth.uid())))
  with check (exists (select 1 from public.portfolio_editors e where e.user_id = (select auth.uid())));

insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values (
 'portfolio-media', 'portfolio-media', true, 36700160,
 array[
   'image/jpeg','image/png','image/webp','image/gif','image/avif',
   'video/mp4','video/webm','video/quicktime'
 ]
)
on conflict (id) do update set public = excluded.public,
  file_size_limit = excluded.file_size_limit,
  allowed_mime_types = excluded.allowed_mime_types;

drop policy if exists "Editors upload portfolio media" on storage.objects;
create policy "Editors upload portfolio media" on storage.objects
  for insert to authenticated with check (
    bucket_id = 'portfolio-media'
    and exists (select 1 from public.portfolio_editors e where e.user_id = (select auth.uid()))
  );
drop policy if exists "Editors delete portfolio media" on storage.objects;
create policy "Editors delete portfolio media" on storage.objects
  for delete to authenticated using (
    bucket_id = 'portfolio-media'
    and exists (select 1 from public.portfolio_editors e where e.user_id = (select auth.uid()))
  );

